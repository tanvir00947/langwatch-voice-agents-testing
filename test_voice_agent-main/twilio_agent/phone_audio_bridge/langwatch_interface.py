"""LangWatch Scenario Integration Interface for Twilio Phone Calls.

Architectural contract for future integration with LangWatch Scenario.
In this architecture:
- The human speaks and listens through their mobile phone via Twilio Media Streams.
- The LangWatch voice model (e.g. Gemini Live / Puck / Aoede) acts as the conversational caller.
- LangWatch Scenario drives the test script, background noise/telephony filters, and barge-in.
- An LLM judge evaluates the human's or agent's responses with telemetry logged to app.langwatch.ai.
"""

from __future__ import annotations

import asyncio
import logging
from typing import Any, Callable, Optional

from twilio_agent.phone_audio_bridge.audio_bridge import AudioBridge
from twilio_agent.phone_audio_bridge.audio_codec import resample_pcm

logger = logging.getLogger("phone_audio_bridge.langwatch")

TWILIO_RATE = 8000
SCENARIO_RATE = 24000  # Default Scenario / Gemini Live sample rate


class LangWatchScenarioBridge(AudioBridge):
    """Audio Bridge connecting Twilio phone streams to LangWatch Scenario.

    Handles real-time sample rate conversion between:
    - Twilio Phone: 8000Hz 16-bit PCM (downsampled from / upsampled to telecom).
    - Scenario Agent: 16000Hz or 24000Hz 16-bit PCM.
    """

    def __init__(
        self,
        scenario_sample_rate: int = SCENARIO_RATE,
        on_transcript_callback: Optional[Callable[[str, str], None]] = None,
    ):
        self.scenario_sample_rate = scenario_sample_rate
        self.on_transcript = on_transcript_callback

        # Queue for audio going to Scenario (from phone)
        self.to_scenario_queue: asyncio.Queue[bytes] = asyncio.Queue(maxsize=200)
        # Queue for audio going to phone (from Scenario agent)
        self.to_phone_queue: asyncio.Queue[bytes] = asyncio.Queue(maxsize=200)

        self._active = False

    async def start(self) -> None:
        self._active = True
        logger.info(
            "LangWatchScenarioBridge active: Bridging Twilio (8kHz) <-> Scenario (%dHz)",
            self.scenario_sample_rate,
        )

    async def on_audio_from_phone(self, pcm_chunk: bytes) -> None:
        """Receive 8kHz PCM audio from phone, resample to Scenario rate, and enqueue."""
        if not self._active or not pcm_chunk:
            return

        # Resample from 8000Hz to Scenario rate (e.g. 24000Hz)
        resampled_chunk = resample_pcm(pcm_chunk, TWILIO_RATE, self.scenario_sample_rate)

        if self.to_scenario_queue.full():
            try:
                self.to_scenario_queue.get_nowait()
            except asyncio.QueueEmpty:
                pass
        self.to_scenario_queue.put_nowait(resampled_chunk)

    async def get_audio_to_phone(self) -> Optional[bytes]:
        """Fetch model audio generated by Scenario, resample to 8kHz, and stream to phone."""
        if not self._active:
            return None
        try:
            pcm_chunk = await asyncio.wait_for(self.to_phone_queue.get(), timeout=0.05)
            # Resample from Scenario rate back to Twilio's 8000Hz
            return resample_pcm(pcm_chunk, self.scenario_sample_rate, TWILIO_RATE)
        except asyncio.TimeoutError:
            return None

    # Methods called by LangWatch Scenario adapter
    async def scenario_read_caller_audio(self) -> bytes:
        """Called by LangWatch Scenario to read caller speech."""
        return await self.to_scenario_queue.get()

    def scenario_feed_agent_audio(self, agent_pcm_chunk: bytes) -> None:
        """Called by LangWatch Scenario to feed voice model response speech."""
        if self.to_phone_queue.full():
            try:
                self.to_phone_queue.get_nowait()
            except asyncio.QueueEmpty:
                pass
        self.to_phone_queue.put_nowait(agent_pcm_chunk)

    async def stop(self) -> None:
        self._active = False
        logger.info("LangWatchScenarioBridge stopped.")


class LangWatchEvaluationPlan:
    """Blueprint for evaluating phone conversation turns with an LLM Judge."""

    def __init__(self, scenario_name: str = "customer_service_inquiry"):
        self.scenario_name = scenario_name
        self.evaluation_criteria = [
            "Politeness and conversational conduct",
            "Response accuracy and adherence to scenario objective",
            "Handling of acoustic noise and interruptions (barge-in)",
            "Response latency and natural turn-taking",
        ]

    def get_judge_prompt(self, transcript: str) -> str:
        """Format the judge evaluation prompt."""
        criteria_str = "\n".join(f"- {c}" for c in self.evaluation_criteria)
        return f"""You are an expert conversational AI evaluator.
Evaluate the following phone conversation transcript according to these criteria:
{criteria_str}

Conversation Transcript:
{transcript}

Provide:
1. Turn-by-turn analysis
2. Score (1-10) for each criterion
3. Overall verdict: PASS or FAIL
"""

